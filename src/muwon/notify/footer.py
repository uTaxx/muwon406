"""텔레그램으로 나가는 모든 글 맨 아래에 붙는 대시보드 링크.

알림을 폰에서 보다가 "지금 얼마야", "꺼야 하나"가 궁금해지면 결국 대시보드를
열어야 한다. 그때 주소를 찾아 헤매게 하지 않으려고 **글마다 링크를 달아 둔다.**

## 왜 한 군데서만 붙이나

내보내는 길이 셋이다 — 알림(TelegramNotifier), 버튼 달린 글(telegram_api.send),
버튼을 누른 뒤 갈아 끼우는 글(telegram_api.edit_text). 각자 붙이면 어느 하나를
빠뜨리고, 빠뜨린 줄도 모른다. 그래서 여기 한 곳에 두고 셋이 같이 쓴다.

## 왜 붙이기 전에 떼나

버튼을 누르면 이미 보낸 글을 통째로 갈아 끼우는데, 그 원본에는 이미 링크가
붙어 있다. 떼지 않고 붙이면 누를 때마다 링크가 한 줄씩 쌓인다.
"""

from __future__ import annotations

import html
import os
import re

#: 텔레그램 한 메시지 길이 제한.
텔레그램한도 = 4096

이름 = "주식매매 관리용 대시보드"
표시 = f"📊 {이름}"

#: GitHub Pages 주소(docs/대시보드_통합.md). 스트림릿에서 옮겨 왔다 —
#: 관리 지점이 다섯이라 답답하다는 말을 듣고 화면 하나로 모았다.
#: MUWON_DASHBOARD_URL 환경변수로 덮어쓸 수 있게 해 둔다. 배포 주소는
#: 우리가 정하는 값이 아니라서 코드를 고치지 않고도 갈아 끼워야 한다.
기본주소 = "https://utaxx.github.io/sdlab_trading/"


def 주소() -> str:
    return (os.environ.get("MUWON_DASHBOARD_URL") or "").strip() or 기본주소


def 블록() -> str:
    """이름만 보이고 주소는 숨는 링크.

    주소를 그대로 노출하면 글 끝이 긴 URL로 어수선해지고, 폰에서는 두세
    줄을 잡아먹는다. 텔레그램 HTML 모드로 이름에 주소를 걸어 둔다."""
    return f'<a href="{html.escape(주소(), quote=True)}">{html.escape(표시)}</a>'


#: 우리가 붙인 링크의 모양. 글 맨 끝에만 온다.
_앵커꼴 = re.compile(r'\s*<a href="[^"]*">\s*' + re.escape(표시) + r'\s*</a>\s*$')

#: 잘라 낸 자리에 반쪽짜리 HTML 실체(&am…)가 남으면 텔레그램이 글 전체를
#: 거절한다. 그러면 알림이 통째로 안 간다.
_반쪽실체 = re.compile(r"&[a-zA-Z#0-9]*$")


def 떼기(글: str) -> str:
    """이미 붙어 있는 링크를 걷어 낸다. 없으면 그대로 돌려준다.

    모양이 셋이라 셋 다 받는다.

    1. **우리가 방금 만든 것** — `<a href=...>📊 …</a>`
    2. **텔레그램이 돌려주는 것** — 버튼을 누르면 화면에 보이는 글자만
       넘어온다. 즉 `📊 …`만 있고 주소는 없다.
    3. **옛 순수 텍스트** — `📊 …` 다음 줄에 주소. HTML로 바꾸기 전에
       보낸 글을 나중에 갈아 끼울 때 만난다.
    """
    글 = 글 or ""
    벗긴것 = _앵커꼴.sub("", 글)
    if 벗긴것 != 글:
        # 1번이었다면 본문도 이스케이프돼 있다. 되돌려야 다시 붙일 때
        # &amp;amp; 처럼 겹치지 않는다.
        return html.unescape(벗긴것).rstrip()
    자리 = 글.rfind(표시)
    return 글 if 자리 < 0 else 글[:자리].rstrip()


def 붙이기(글: str, 한도: int = 텔레그램한도) -> str:
    """글 맨 아래에 링크를 붙인다. 여러 번 불러도 링크는 하나다.

    한도를 넘으면 **링크를 빼는 게 아니라 본문을 줄인다.** 링크가 빠지면
    "항상 달려 있다"는 약속이 조용히 깨지는데, 그건 붙어 있다고 믿는 쪽이
    더 위험하다. 잘린 본문은 눈에 보이지만 없는 링크는 안 보인다.

    돌려주는 것은 **HTML**이다. 보내는 쪽이 parse_mode=HTML로 넣어야 한다."""
    몸통 = html.escape(떼기(글), quote=False)
    꼬리 = "\n\n" + 블록()
    남는자리 = 한도 - len(꼬리)
    if len(몸통) > 남는자리:
        말줄임 = "…"
        몸통 = _반쪽실체.sub("", 몸통[: max(남는자리 - len(말줄임), 0)]) + 말줄임
    return 몸통 + 꼬리
