기본이순위 = "max_drawdown"
기본삼순위 = "total_return"


@dataclass(frozen=True)
class 판단기준:
    """1순위부터 3순위까지. 순위를 내는 자리는 전부 이것을 지나간다."""

    일순위: str = 기본일순위
    이순위: str = 기본이순위
    삼순위: str = 기본삼순위

    @property
    def 열쇠들(self) -> tuple[str, str, str]:
        return (self.일순위, self.이순위, self.삼순위)

    @property
    def 지침들(self) -> list[지침]:
        """아는 것만, 순서대로. 모르는 열쇠와 중복은 빠진다."""
        나온것: list[지침] = []
        본것: set[str] = set()
        for 열쇠 in self.열쇠들:
            ㄱ = 찾기(열쇠)
            if ㄱ is None or ㄱ.갈래 != 순위갈래 or ㄱ.열쇠 in 본것:
                continue
            나온것.append(ㄱ)
            본것.add(ㄱ.열쇠)
        return 나온것

    @property
    def 성한가(self) -> bool:
        """세 자리가 다 아는 순위 지침이고 서로 다른가."""
        return len(self.지침들) == 3

    @property
    def 탈(self) -> str:
        """성하지 않으면 왜 그런지. 성하면 빈 글자."""
        말 = []
        본것: set[str] = set()
        for 자리, 열쇠 in zip(("1순위", "2순위", "3순위"), self.열쇠들, strict=True):
            ㄱ = 찾기(열쇠)
            if ㄱ is None:
                말.append(f"{자리}에 모르는 지침이 적혀 있습니다: {열쇠}")
            elif ㄱ.갈래 != 순위갈래:
                말.append(f"{자리}의 {ㄱ.이름}은 순위를 매길 수 없는 지침입니다")
            elif ㄱ.열쇠 in 본것:
                말.append(f"{자리}가 앞 순위와 같습니다: {ㄱ.이름}")
            else:
                본것.add(ㄱ.열쇠)
        return " ".join(말)

    def 정렬키(self, 성적):
        """`sorted`에 그대로 넣는 키. 앞자리가 좋을수록 앞에 온다.

        **못 잰 값은 뒤로 보낸다.** 0으로 채우면 못 잰 것이 0%인 것처럼
        섞여서, 표에서 그 둘을 구별할 수 없다."""
        키: list[float] = []
        for ㄱ in self.지침들:
            칸 = ㄱ.칸(성적)
            키.append(1.0 if 칸 is None else 0.0)
            키.append(0.0 if 칸 is None else -칸)
        return tuple(키)

    def 못잰지침(self, 성적) -> list[str]:
        """이 성적에서 값을 못 낸 지침의 이름."""
        return [ㄱ.이름 for ㄱ in self.지침들 if ㄱ.칸(성적) is None]

    def 설명글(self) -> str:
        """화면과 시트에 같이 적는 한 줄.

        조사를 글자로 박지 않는다. 지침 이름이 설정에서 오므로 무엇이 올지
        모른다. "누적 수익률으로"가 나오는 자리다."""
        from muwon.text import 으로로, 을를

        ㄷ = self.지침들
        if not ㄷ:
            return "판단 지침이 설정되지 않았습니다."
        if len(ㄷ) == 1:
            return f"{ㄷ[0].이름}{으로로(ㄷ[0].이름)} 순위를 매깁니다."
        말 = f"{ㄷ[0].이름}{을를(ㄷ[0].이름)} 먼저 보고, 비슷하면 {ㄷ[1].이름}"
        끝 = ㄷ[1].이름
        if len(ㄷ) > 2:
            말 += f", 그다음 {ㄷ[2].이름}"
            끝 = ㄷ[2].이름
        return 말 + f"{으로로(끝)} 순서를 정합니다."


