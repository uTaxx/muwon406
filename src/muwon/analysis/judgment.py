지침표: dict[str, 지침] = {ㄱ.열쇠: ㄱ for ㄱ in 순위지침들 + 확인지침들}


def 찾기(열쇠: str) -> 지침 | None:
    return 지침표.get(str(열쇠 or "").strip())


def 이름(열쇠: str) -> str:
    """사람에게 보여 줄 이름. 모르는 열쇠면 열쇠를 그대로 돌려준다.

    **모르는 값을 조용히 기본값으로 바꾸지 않는다.** 시트에 오타가 들어 있으면
    그 오타가 화면에 보여야 어디를 고칠지 안다."""
    ㄱ = 찾기(열쇠)
    return ㄱ.이름 if ㄱ else str(열쇠 or "")


