"""전략을 견줄 때 무엇을 먼저 보나. 판단 지침 목록과 그 순위.

## 이 파일이 있는 이유

판단 기준이 지금까지 문장으로만 있었다. CLAUDE.md에 "1순위 판단 기준은
평균이 아니라 가장 나빴던 구간이다"라고 적혀 있고, 사람은 그것을 지켰다.

그런데 **순위를 매기는 코드는 수익률로 정렬하고 있었다**(`period_check.
비교총평`과 `strategy_fit.구간순위.차례`). 적힌 것과 도는 것이 달랐고,
어긋난 것을 아무것도 빨갛게 만들지 않았다. 화면의 순위표와 매일 검토의
후보가 그 정렬을 그대로 쓴다.

그래서 지침을 값으로 만들었다. 순위를 내는 자리는 전부 이 파일을 지나가고,
무엇을 먼저 보는지는 대시보드에서 고른다.

## 지침은 두 갈래다

**순위 지침**은 계산해서 줄을 세울 수 있는 것이다. 1순위부터 3순위까지
고르고, 앞 순위가 비기면 다음 순위로 가른다.

**확인 지침**은 계산으로 줄을 세울 수 없고 사람이 봐야 하는 것이다.
대조군을 이겼는지, 이웃 설정에서도 같은지 같은 것이다. 이런 것을 목록에서
빼 두면 판단할 때 잊게 되므로 화면에 같이 적는다.

## 비기는 폭

수익률 같은 소수점 값은 두 전략이 정확히 같을 일이 없다. 폭을 안 두면
2순위와 3순위가 영영 안 쓰이고, 0.01%p 차이가 순위를 가르게 된다. 그래서
지침마다 "이 정도 차이는 같다고 본다"는 폭을 둔다.

폭으로 자르는 방식이라 칸의 경계는 임의다. 폭이 1%p일 때 -0.4%와 -1.1%는
다른 칸에 들어간다. 정확한 동률 판정이 아니라 **소수점 차이로 순위가
뒤집히는 것을 막는 장치**다.

## 여기서 하지 않는 것

**이 파일은 "바꿔라"라고 말하지 않는다.** 줄을 세우는 규칙만 정한다. 무엇을
쓸지는 사람이 정하고, 실제로 바꾸는 것은 워크플로에서만 한다.
"""

from __future__ import annotations

from collections.abc import Callable
from dataclasses import dataclass, replace

순위갈래 = "순위"
확인갈래 = "확인"


@dataclass(frozen=True)
class 지침:
    """판단 지침 하나.

    `값내기`는 **클수록 좋은 값**을 돌려준다. 최대낙폭처럼 작을수록 좋은
    값은 음수라서 그대로 클수록 좋다. 방향을 여기서 통일해 두지 않으면
    부르는 쪽마다 부호를 뒤집게 되고, 한 곳만 빠뜨려도 순위가 조용히
    뒤집힌다.

    못 재는 경우에는 None을 돌려준다. **0으로 채우지 않는다.** 구간이 하나도
    없어서 못 잰 것과 0%인 것은 다른 말이다.
    """

    열쇠: str
    이름: str
    설명: str
    갈래: str = 순위갈래
    단위: str = ""
    #: 이만큼 차이는 같다고 본다. 0이면 값이 다르면 무조건 다르다고 본다.
    비긴폭: float = 0.0
    값내기: Callable[[object], float | None] | None = None

    def 값(self, 성적) -> float | None:
        if self.값내기 is None:
            return None
        try:
            return self.값내기(성적)
        except (AttributeError, TypeError, ZeroDivisionError, IndexError):
            # 성적 모양이 다르면 못 잰 것으로 둔다. 여기서 터지면 순위표가
            # 통째로 안 나온다. 한 줄을 못 재는 것보다 훨씬 나쁘다.
            return None

    def 칸(self, 성적) -> float | None:
        """비긴 폭으로 자른 값. 같은 칸이면 비긴 것으로 본다."""
        ㄱ = self.값(성적)
        if ㄱ is None:
            return None
        if self.비긴폭 <= 0:
            return ㄱ
        return ㄱ // self.비긴폭


def _최악구간(성적) -> float | None:
    ㄱ = 성적.최악토막
    return None if ㄱ is None else float(ㄱ[1])


def _플러스구간비율(성적) -> float | None:
    구간들 = list(getattr(성적, "구간들", []) or [])
    if not 구간들:
        return None
    return sum(1 for _, ㄱ in 구간들 if ㄱ > 0) / len(구간들) * 100


