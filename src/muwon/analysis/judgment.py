def 줄세우기(성적들, 기준: 판단기준 | None = None, 성적꺼내기=None) -> list:
    """판단 기준으로 정렬한 목록.

    `성적꺼내기`를 주면 항목에서 성적을 꺼내 쓴다. 순위표의 줄처럼 성적을
    품고 있는 것을 그대로 넘길 수 있다."""
    ㄱ = 기준 or 기본기준
    꺼내기 = 성적꺼내기 or (lambda ㅈ: ㅈ)
    return sorted(성적들, key=lambda ㅈ: ㄱ.정렬키(꺼내기(ㅈ)))


def 시트에서(시트설정, 기본: 판단기준 | None = None) -> 판단기준:
    """시트 `설정` 탭의 세 칸을 읽어 판단 기준으로 만든다.

    시트를 못 읽었거나 값이 성하지 않으면 **기본값으로 돌아간다.** 순위를
    아예 못 내면 검토가 통째로 멈추는데, 그것이 지침 하나가 옛 값인 것보다
    나쁘다. 대신 되돌아갔다는 사실은 부르는 쪽이 `탈`로 확인할 수 있다."""
    바탕 = 기본 or 기본기준
    if 시트설정 is None:
        return 바탕
    try:
        고른것 = replace(
            바탕,
            일순위=str(시트설정.가져오기("rank_1st") or 바탕.일순위),
            이순위=str(시트설정.가져오기("rank_2nd") or 바탕.이순위),
            삼순위=str(시트설정.가져오기("rank_3rd") or 바탕.삼순위),
        )
    except (AttributeError, KeyError):
        return 바탕
    return 고른것 if 고른것.성한가 else 바탕
