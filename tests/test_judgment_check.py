"""판단 지침 검증이 지켜야 하는 것을 고정한다.

**네트워크에 나가지 않는다.** 구간을 손으로 만들어 넣는다.

여기서 지키는 것은 "어느 지침이 낫나"가 아니다. 그건 계산해 봐야 아는
것이고 자료가 바뀌면 답도 바뀐다. 고정하는 것은 **재는 방법이 틀리지
않는 것**이다. 미래를 안 보는 것, 아무것도 안 한 전략을 1등으로 세우지
않는 것, 대조군을 지침과 같은 기준으로 거르는 것 셋이다.
"""

from datetime import date, timedelta

import pytest

from muwon.analysis import judgment_check as 검증
from muwon.analysis.window_perf import 구간


def _잰것(시작: date, 수익률: float, 매수수: int = 3,
        낙폭: float | None = None):
    # 낙폭을 수익률에서 끌어낸다. 전부 같은 값으로 두면 낙폭 지침에서
    # 모든 전략이 동점이 되고, 그러면 이름순으로 뽑혀서 시험이 엉뚱한
    # 것을 잡는다. 실제로 그랬다.
    if 낙폭 is None:
        낙폭 = min(-0.5, 수익률)
    return 검증.잰구간(
        구간=구간(시작일=시작, 끝일=시작 + timedelta(days=4),
                수익률=수익률, 최대낙폭=낙폭),
        매수수=매수수,
    )


def _구간표(설정: dict[str, list[float]], 매수수: dict[str, int] | None = None):
    """{전략키: [구간별 수익률]} → 구간표."""
    매수수 = 매수수 or {}
    첫날 = date(2021, 1, 4)
    return {
        키: [_잰것(첫날 + timedelta(days=7 * i), ㄱ, 매수수.get(키, 3))
            for i, ㄱ in enumerate(값들)]
        for 키, 값들 in 설정.items()
    }


# ── 아무것도 안 한 전략을 1등으로 세우지 않는다 ───────────────


def test_거의_안_산_전략은_후보에서_뺀다():
    """**이게 이 파일에서 제일 중요하다.**

    처음 계산했을 때 265번 중 253번을 5년 거래 1건짜리 전략이 가져갔다.
    안 사면 수익률이 0이고, 0은 어느 마이너스보다 크다. 지킨 것이 아니라
    아무것도 안 한 것인데 지침은 그것을 구별하지 못한다."""
    돌아볼 = 3
    구간표 = _구간표(
        {"안사는것": [0.0] * 8, "사는것": [-1.0, 2.0] * 4},
        매수수={"안사는것": 0, "사는것": 5},
    )
    지침 = next(ㅈ for ㅈ in 검증.지침들 if ㅈ.키 == "worst")
    성적 = 검증.워크포워드(구간표, 지침, 돌아볼)
    assert 성적 is not None
    고른것 = {ㅍ.고른키 for ㅍ in 성적.판정들}
    assert "안사는것" not in 고른것, "아무것도 안 산 전략이 뽑혔습니다"


def test_후보가_하나도_없으면_판정을_안_한다():
    """억지로 하나 고르면 그 숫자가 지침의 성적으로 섞인다."""
    구간표 = _구간표({"안사는것": [0.0] * 8}, 매수수={"안사는것": 0})
    지침 = next(ㅈ for ㅈ in 검증.지침들 if ㅈ.키 == "worst")
    성적 = 검증.워크포워드(구간표, 지침, 3)
    assert 성적 is None or 성적.판정수 == 0 or 성적.못한판정 > 0


# ── 미래를 보지 않는다 ────────────────────────────────────────


def test_판정에_그_구간과_뒤를_안_쓴다():
    """i번째 구간을 고를 때 i번째 성적을 보면 안 된다.

    마지막 구간에만 크게 좋은 전략을 넣어 둔다. 미래를 본다면 그 전략을
    골라야 하고, 안 본다면 고를 수 없다."""
    돌아볼 = 3
    구간표 = _구간표({
        "꾸준한것": [1.0] * 8,
        "마지막에만좋은것": [-5.0] * 7 + [99.0],
    })
    for 지침 in 검증.지침들:
        성적 = 검증.워크포워드(구간표, 지침, 돌아볼)
        if 성적 is None:
            continue
        마지막 = [ㅍ for ㅍ in 성적.판정들 if ㅍ.다음수익률 > 50]
        assert not 마지막, (
            f"{지침.이름}이 마지막 구간의 성적을 미리 보고 골랐습니다")


def test_돌아본_구간만으로_고른다():
    """앞의 구간을 바꾸면 판정이 바뀌고, 뒤를 바꾸면 안 바뀌어야 한다."""
    돌아볼 = 3
    기본 = {"가": [1.0, 1.0, 1.0, 0.5, 0.5], "나": [-9.0, -9.0, -9.0, 0.5, 0.5]}
    지침 = next(ㅈ for ㅈ in 검증.지침들 if ㅈ.키 == "worst")
    먼저 = 검증.워크포워드(_구간표(기본), 지침, 돌아볼)
    뒤만바꿈 = dict(기본)
    뒤만바꿈["나"] = [-9.0, -9.0, -9.0, 7.0, 7.0]
    나중 = 검증.워크포워드(_구간표(뒤만바꿈), 지침, 돌아볼)
    assert 먼저 and 나중
    assert ([ㅍ.고른키 for ㅍ in 먼저.판정들]
            == [ㅍ.고른키 for ㅍ in 나중.판정들]), (
        "뒤 구간을 바꿨는데 앞의 판정이 달라졌습니다. 미래를 보고 있습니다.")


# ── 대조군은 지침과 같은 기준으로 거른다 ──────────────────────


def test_무작위_대조군도_안_산_전략을_안_고른다():
    """대조군만 아무 전략이나 고르면 지침이 쉬운 상대와 견주는 셈이 된다."""
    구간표 = _구간표(
        {"안사는것": [0.0] * 10, "사는것": [-2.0, 3.0] * 5},
        매수수={"안사는것": 0, "사는것": 5},
    )
    대조 = 검증.무작위대조군(구간표, 돌아볼=3, 횟수=20)
    assert 대조 is not None
    # 안 사는 것이 뽑혔다면 값이 전부 0이라 중앙값도 0이 된다.
    assert 대조.중앙값 != 0.0 or 대조.최악 != 0.0


def test_대조군_셋을_다_낼_수_있다():
    구간표 = _구간표({"가": [1.0, -2.0] * 5, "나": [0.5, -1.0] * 5})
    assert 검증.무작위대조군(구간표, 돌아볼=3, 횟수=10) is not None
    assert 검증.전체평균대조군(구간표, 돌아볼=3) is not None
    assert 검증.안바꾼대조군(구간표, "가", 돌아볼=3) is not None
    assert 검증.안바꾼대조군(구간표, "없는키", 돌아볼=3) is None


# ── 순위 기준 ────────────────────────────────────────────────


def test_지침_순위도_가장_나빴던_것을_먼저_본다():
    """전략을 고를 때와 같은 기준이다. 지침을 고르는 자리에서만 평균을
    먼저 보면 앞뒤가 안 맞는다."""
    구간표 = _구간표({"가": [2.0, -1.0] * 8, "나": [1.0, -0.5] * 8,
                 "다": [3.0, -6.0] * 8})
    성적들 = 검증.모두재기(구간표, 돌아볼=4)
    if len(성적들) < 2:
        pytest.skip("견줄 지침이 모자랍니다")
    최악들 = [ㅅ.최악 for ㅅ in 성적들]
    assert 최악들 == sorted(최악들, reverse=True)


