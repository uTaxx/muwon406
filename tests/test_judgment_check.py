def test_전략_코드가_이_모듈을_안_부른다():
    """지침을 재는 자리와 매매하는 자리가 섞이면, "이 결과로 지침이
    바뀌지 않습니다"가 거짓말이 된다."""
    import pathlib

    뿌리 = pathlib.Path(__file__).resolve().parent.parent / "src" / "muwon"
    for 파일 in (뿌리 / "strategy").rglob("*.py"):
        assert "judgment_check" not in 파일.read_text(encoding="utf-8"), (
            f"{파일.name}이 지침 검증을 부릅니다")
